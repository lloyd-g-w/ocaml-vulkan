@dataclass
class Context:
    registry: Registry
    bits_to_flags: dict[str, str]
    composite_aliases: dict[str, str]
    broken_refs: set[tuple[str, str]]
    order: list[str]

    @classmethod
    def make(cls, registry: Registry) -> "Context":
        bits_to_flags: dict[str, str] = {}
        for bitmask in registry.bitmasks.values():
            if not bitmask.alias and bitmask.bits:
                bits_to_flags.setdefault(bitmask.bits, bitmask.name)
        # Empty flag-bit enums are not named in the typedef's requires
        # attribute.  Pair those by the registry's Flags/FlagBits spelling.
        def flag_stem(name: str) -> str:
            return name.replace("FlagBits", "Flags").replace("Flags", "")
        for bitmask in registry.bitmasks.values():
            if bitmask.alias or bitmask.bits:
                continue
            matches = [
                enum_name for enum_name, enum in registry.enums.items()
                if enum.kind == "bitmask" and flag_stem(enum_name) == flag_stem(bitmask.name)
            ]
            if len(matches) == 1:
                bits_to_flags[matches[0]] = bitmask.name
        aliases = {name: c.alias for name, c in registry.composites.items() if c.alias}
        provisional = cls(registry, bits_to_flags, aliases, set(), [])
        order, broken = topological_order(provisional)
        provisional.order = order
        provisional.broken_refs = broken
        provisional.validate_types()
        return provisional

    def canonical_composite(self, name: str) -> str:
        seen: set[str] = set()
        while name in self.composite_aliases and name not in seen:
            seen.add(name)
            name = self.composite_aliases[name]
        return name

    def enum_module(self, ctype: str) -> str:
        seen: set[str] = set()
        while ctype in self.registry.enums and self.registry.enums[ctype].alias and ctype not in seen:
            seen.add(ctype)
            ctype = self.registry.enums[ctype].alias or ctype
        if ctype in self.bits_to_flags:
            return naming.module_name(self.bits_to_flags[ctype])
        return naming.module_name(ctype)

    def kind(self, ctype: str) -> str:
        if ctype == "PFN_vkVoidFunction":
            return "pointer"
        if ctype in BASE_TYPES:
            if ctype == "VkBool32":
                return "bool"
            if ctype in {"float", "double"}:
                return "float"
            if ctype == "char":
                return "char"
            if ctype == "void":
                return "void"
            return "int"
        if ctype in self.registry.bitmasks or ctype in self.bits_to_flags:
            return "flags"
        if ctype in self.registry.enums:
            return "enum"
        if ctype in self.registry.handles:
            return "handle"
        if ctype in self.registry.composites:
            target = self.registry.composites[ctype]
            if target.alias and target.alias in self.registry.composites:
                target = self.registry.composites[self.canonical_composite(ctype)]
            return target.kind
        if ctype in self.registry.funcpointers:
            return "funcpointer"
        if ctype in OPAQUE_BASETYPES:
            return OPAQUE_BASETYPES[ctype]
        if ctype in EXTERNAL_TYPES:
            return EXTERNAL_TYPES[ctype]
        if ctype.startswith("StdVideo"):
            # StdVideo enums occur by value; all other external StdVideo
            # declarations occur behind pointers.
            if any(x in ctype for x in ("Profile", "Level")):
                return "external_enum"
            return "opaque"
        raise KeyError(ctype)

    def base_typ(self, ctype: str, *, owner: str | None = None) -> str:
        if owner is not None and (owner, ctype) in self.broken_refs:
            return "void"
        if ctype in BASE_TYPES:
            return BASE_TYPES[ctype]
        kind = self.kind(ctype)
        if kind in {"enum", "flags"}:
            return f"{self.enum_module(ctype)}.t"
        if kind == "handle":
            return f"{naming.module_name(ctype)}.t"
        if kind in {"struct", "union"}:
            target = self.canonical_composite(ctype)
            # The module value [X.t] already has type [X.t structure typ]
            # (or union typ); no extra structure constructor belongs here.
            if owner == target:
                return "t"
            return f"{naming.module_name(target)}.t"
        if kind == "funcpointer":
            return f"{naming.module_name(ctype)}.opt"
        if kind in {"pointer"}:
            return "ptr void"
        if kind == "opaque":
            return "void"
        if kind in {"uint32", "external_enum"}:
            return "Vk_base.uint32" if kind == "uint32" else "Vk_base.int32"
        if kind == "uint64":
            return "Vk_base.uint64"
        if kind == "int32":
            return "Vk_base.int32"
        raise KeyError(ctype)

    def foreign_typ(self, member: Member, *, owner: str | None = None,
                    strings: bool = False) -> str:
        # Command and callback const-char parameters use ctypes' safe string
        # views; struct members remain pointers so NULL is representable.
        if strings and member.ctype == "char" and member.pointer_depth == 1 and member.const:
            typ = "string_opt" if any(member.optional) else "string"
        else:
            typ = self.base_typ(member.ctype, owner=owner)
            depth = member.pointer_depth
            if owner is not None and (owner, member.ctype) in self.broken_refs:
                # The broken edge represents the whole pointed-to opaque value.
                depth = max(depth, 1)
            for _ in range(depth):
                typ = f"ptr ({typ})"
        if strings and member.arrays:
            # Array parameters decay to pointers in C function prototypes.
            for dim in reversed(member.arrays[1:]):
                typ = f"array {self.array_size(dim)} ({typ})"
            typ = f"ptr ({typ})"
        else:
            for dim in reversed(member.arrays):
                typ = f"array {self.array_size(dim)} ({typ})"
        return typ

    def value_type(self, member: Member, *, owner: str | None = None,
                   strings: bool = False) -> str:
        string_view = strings and member.ctype == "char" and member.pointer_depth == 1 and member.const
        if string_view:
            typ = "string option" if any(member.optional) else "string"
        elif owner is not None and (owner, member.ctype) in self.broken_refs:
            typ = "unit"
        elif member.ctype in BASE_VALUE_TYPES:
            typ = BASE_VALUE_TYPES[member.ctype]
        else:
            kind = self.kind(member.ctype)
            if kind in {"enum", "flags"}:
                typ = f"{self.enum_module(member.ctype)}.t"
            elif kind == "handle":
                typ = f"{naming.module_name(member.ctype)}.t"
            elif kind == "struct":
                typ = f"{naming.module_name(self.canonical_composite(member.ctype))}.t Ctypes.structure"
            elif kind == "union":
                typ = f"{naming.module_name(self.canonical_composite(member.ctype))}.t Ctypes.union"
            elif kind == "funcpointer":
                typ = f"{naming.module_name(member.ctype)}.fn option"
            elif kind in {"pointer", "opaque"}:
                typ = "unit" if kind == "opaque" else "unit Ctypes.ptr"
            elif kind in {"uint32", "uint64", "int32", "external_enum"}:
                typ = "int"
            else:
                raise KeyError(member.ctype)
        for _ in range(0 if string_view else member.pointer_depth):
            typ = f"{typ} Ctypes.ptr"
        if strings and member.arrays:
            for _ in member.arrays[1:]:
                typ = f"{typ} Ctypes.CArray.t"
            typ = f"{typ} Ctypes.ptr"
        else:
            for _ in member.arrays:
                typ = f"{typ} Ctypes.CArray.t"
        return typ

    def array_size(self, expression: str) -> int:
        expression = expression.strip()
        if expression.isdigit():
            return int(expression)
        value = self.registry.constants.get(expression)
        if not isinstance(value, int):
            raise ValueError(f"unknown/non-integer array dimension {expression}")
        return value

    def validate_types(self) -> None:
        unknown: dict[str, list[str]] = {}
        def check(ctype: str, where: str) -> None:
            try:
                self.kind(ctype)
            except KeyError:
                unknown.setdefault(ctype, []).append(where)
        for comp in self.registry.composites.values():
            for member in comp.members:
                check(member.ctype, f"{comp.name}.{member.name}")
        for fp in self.registry.funcpointers.values():
            check(fp.result.ctype, f"{fp.name} result")
            for param in fp.params:
                check(param.ctype, f"{fp.name}.{param.name}")
        for command in self.registry.commands.values():
            if command.result:
                check(command.result.ctype, f"{command.name} result")
            for param in command.params:
                check(param.ctype, f"{command.name}.{param.name}")
        if unknown:
            details = "; ".join(f"{name}: {', '.join(wheres[:4])}" for name, wheres in sorted(unknown.items()))
            raise ValueError(f"unknown C types in registry: {details}")

        # P1-3 (DESIGN.md §7/§13): every generated struct that declares an
        # expected sType constant (`values="VK_STRUCTURE_TYPE_..."` in the
        # registry) must resolve it to a real VkStructureType value -- if it
        # doesn't, `make` would silently fall back to StructureType.of_int 0
        # (= VK_STRUCTURE_TYPE_APPLICATION_INFO) with no error, exactly the
        # P1-3 bug (vulkansc-only/disabled types reachable but their sType
        # *value* skipped). Structs whose sType member has no `values=` at
        # all (VkBaseInStructure/VkBaseOutStructure -- generic pNext-chain
        # link types with no single fixed sType) are not an error: there is
        # no declared value to fail to resolve.
        structure_type_enum = self.registry.enums.get("VkStructureType")
        structure_values = {v.name for v in structure_type_enum.values} if structure_type_enum else set()
        unresolved_stype: list[str] = []
        for name, comp in self.registry.composites.items():
            if comp.alias or comp.kind != "struct":
                continue
            for member in comp.members:
                if member.name == "sType" and member.values:
                    wanted = member.values.split(",")[0]
                    if wanted not in structure_values:
                        unresolved_stype.append(f"{name} (wants {wanted})")
        if unresolved_stype:
            details = "; ".join(sorted(unresolved_stype))
            raise ValueError(
                "generated structs with an sType member but no resolvable "
                f"StructureType value (reachability/enum-value bug): {details}"
            )


def _dependency_edges(ctx: Context) -> tuple[dict[str, set[str]], dict[tuple[str, str], bool]]:
    registry = ctx.registry
    nodes = {
        name for name, c in registry.composites.items() if not c.alias
    } | set(registry.funcpointers)
    deps = {name: set() for name in nodes}
    breakable: dict[tuple[str, str], bool] = {}

    def add(owner: str, member: Member) -> None:
        dep = member.ctype
        if dep in registry.composites:
            dep = ctx.canonical_composite(dep)
        if dep not in nodes or dep == owner:
            return
        deps[owner].add(dep)
        # A pointer can safely be represented opaquely to break the handful of
        # callback/structure cycles in the registry.
        can_break = member.pointer_depth > 0
        breakable[(owner, dep)] = breakable.get((owner, dep), False) or can_break

    for name, comp in registry.composites.items():
        if comp.alias:
            continue
        for member in comp.members:
            add(name, member)
    for name, fp in registry.funcpointers.items():
        add(name, fp.result)
        for param in fp.params:
            add(name, param)
    return deps, breakable


def topological_order(ctx: Context) -> tuple[list[str], set[tuple[str, str]]]:
    deps, breakable = _dependency_edges(ctx)
    remaining = set(deps)
    ordered: list[str] = []
    broken: set[tuple[str, str]] = set()
    while remaining:
        ready = sorted(name for name in remaining if not (deps[name] & remaining))
        if ready:
            ordered.extend(ready)
            remaining.difference_update(ready)
            continue
        choices = sorted(
            (owner, dep) for owner in remaining for dep in (deps[owner] & remaining)
            if breakable.get((owner, dep), False)
        )
        if not choices:
            cycle = ", ".join(sorted(remaining)[:12])
            raise ValueError(f"unbreakable by-value type dependency cycle: {cycle}")
        owner, dep = choices[0]
        deps[owner].remove(dep)
        # Resolution checks the original C type, which may be an alias.
        for comp_name, comp in ctx.registry.composites.items():
            if comp_name == owner:
                for member in comp.members:
                    if ctx.canonical_composite(member.ctype) == dep:
                        broken.add((owner, member.ctype))
        if owner in ctx.registry.funcpointers:
            fp = ctx.registry.funcpointers[owner]
            for member in (fp.result, *fp.params):
                if ctx.canonical_composite(member.ctype) == dep:
                    broken.add((owner, member.ctype))
    aliases = sorted(
        (name for name, comp in ctx.registry.composites.items() if comp.alias),
        key=lambda name: (ctx.canonical_composite(name), name),
    )
    return ordered + aliases, broken


def resolve_enum_values(ctx: "Context", values: list[EnumValue]) -> list[tuple[EnumValue, int]]:
    """Resolve every value/alias in `values` to a concrete int, chasing alias
    chains across the whole registry (an extension can alias a value defined
    by a different enum block, e.g. a promoted KHR suffix). Shared by
    emit_enums.py (OCaml enum modules) and emit_enum_values.py (the golden
    C-name -> OCaml-int table checked by test_enum_values.ml), so both sides
    of that check agree on what "resolved" means by construction."""
    global_values: dict[str, int] = {}
    pending: list[EnumValue] = []
    for enum in ctx.registry.enums.values():
        for value in enum.values:
            if isinstance(value.value, int):
                global_values.setdefault(value.name, value.value)
            elif value.alias:
                pending.append(value)
    changed = True
    while changed and pending:
        changed = False
        rest: list[EnumValue] = []
        for value in pending:
            if value.alias in global_values:
                global_values[value.name] = global_values[value.alias]
                changed = True
            else:
                rest.append(value)
        pending = rest
    out = []
    for value in values:
        resolved = value.value if isinstance(value.value, int) else global_values.get(value.alias or "")
        if isinstance(resolved, int):
            out.append((value, resolved))
    return out



SPEC_MAN = "https://registry.khronos.org/vulkan/specs/latest/man/html/"


def spec_doc(cname: str, prefix: str = "") -> str:
    """odoc comment linking a generated item to its Khronos reference page."""
    return f"(** {prefix}{{{{:{SPEC_MAN}{cname}.html}}[{cname}]}} *)"


def ocaml_int(value: int) -> str:
    # OCaml int literals are at most 63 bits on the supported targets.  Render
    # unsigned C spellings through their signed int64 bit pattern.
    if -(1 << 62) <= value < (1 << 62):
        return str(value)
    bits = value & ((1 << 64) - 1)
    signed = bits if bits < (1 << 63) else bits - (1 << 64)
    return f"Int64.to_int {signed}L"


def ocaml_string(value: str) -> str:
    # JSON escaping is accepted by OCaml for the registry's ASCII strings.
    return json.dumps(value, ensure_ascii=True)


def write_generated(path: Path, body: str) -> None:
    content = HEADER + body
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text() if path.exists() else None
    if old != content:
        path.write_text(content)
